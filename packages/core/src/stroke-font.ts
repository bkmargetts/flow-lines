/** Advance (em widths) for one glyph at unit size: glyph box + a tracking gap. */
const ADVANCE = GLYPH_W + 1.6;

/** Width of `text` when set at `size` px (cap height = size). */
export function textWidth(text: string, size: number): number {
  const s = size / GLYPH_H;
  return Math.max(0, text.length * ADVANCE * s - 1.6 * s);
}

/**
 * Lay out `text` as plottable polylines with its top-left at (x, y) and cap
 * height `size` px. Unknown chars fall back to a space. Returns one polyline per
 * pen stroke.
 */
export function textToStrokes(text: string, x: number, y: number, size: number): Point[][] {
  const s = size / GLYPH_H;
  const out: Point[][] = [];
  let penX = x;
  for (const raw of text) {
    const ch = raw.toUpperCase();
    const glyph = G[ch] ?? G[' '];
    for (const stroke of glyph) {
      out.push(stroke.map(([gx, gy]) => ({ x: penX + gx * s, y: y + gy * s })));
    }
    penX += ADVANCE * s;
  }
  return out;
}
